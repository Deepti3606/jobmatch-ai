export function toMarkdown(r, job) {
  const L = (a) => (a.length ? a.map((x) => `- ${x}`).join("\n") : "- None");
  return `# JobMatch AI report${job ? ` — ${job}` : ""}

**Match score (AI estimate): ${r.match_score}%**

## Why this score
${r.summary}

## You match
${L(r.matching_skills)}

## You could improve
${L(r.missing_skills)}

## ATS keywords (add only if genuinely true)
${r.ats_keywords.join(", ") || "None"}

## Experience & qualifications
${L(r.experience_match)}

## Resume suggestions
${r.resume_suggestions.map((s) => `- **${s.title}**: ${s.detail}${s.example ? `\n  - Example: ${s.example}` : ""}`).join("\n")}

## Learning roadmap
${r.learning_recommendations.map((l, i) => `${i + 1}. ${l.skill} (${l.priority}) — ${l.why}`).join("\n")}

_Generated by JobMatch AI. The score is an estimate, not a guarantee of an interview or job._
`;
}
